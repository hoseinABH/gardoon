export function toDemoSummary(g: GroupDetail): GroupSummary {
  const completed = g.rounds.filter((r) => r.status === "SETTLED").length;
  return {
    id: g.id,
    title: g.title,
    ownerId: g.ownerId,
    ownerName: g.ownerName,
    calculationMode: g.calculationMode,
    baseAmount: g.baseAmount,
    estimatedPotAmount: g.totalPotAmount,
    estimatedPerMemberShare: g.perMemberShare,
    currency: g.currency,
    cycleInterval: g.cycleInterval,
    jalaliDueDay: g.jalaliDueDay,
    startDate: g.startDate,
    gracePeriodHours: g.gracePeriodHours,
    status: g.status,
    inviteCode: g.inviteCode,
    memberCount: g.members.length,
    completedRounds: completed,
    totalRounds: g.rounds.length,
    createdAt: g.createdAt,
  };
}
